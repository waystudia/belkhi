create table public.belkhi_journal(id bigint generated always as identity primary key, at timestamptz default now(), action text not null, entity text not null, label text not null);
alter table public.belkhi_journal enable row level security;
revoke all on public.belkhi_journal from anon,authenticated,public;
grant select on public.belkhi_journal to authenticated;
create policy owner_log on public.belkhi_journal for select to authenticated using ((auth.jwt()->'app_metadata'->>'belkhi_role')='owner');
create schema if not exists belkhi_private;
create function belkhi_private.audit() returns trigger language plpgsql security definer set search_path='' as $$
declare item jsonb;
begin
 item:=case when TG_OP='DELETE' then to_jsonb(old) else to_jsonb(new) end;
 insert into public.belkhi_journal(action,entity,label) values(tg_op,tg_table_name,coalesce(item->>'name',item->>'kind',item->>'id'));
 return null;
end $$;
revoke all on function belkhi_private.audit() from public,anon,authenticated;
do $$ declare t text; begin
 foreach t in array array['belkhi_people','belkhi_bids','belkhi_demo_tenders'] loop
 execute format('alter table public.%I enable row level security',t);
 execute format('revoke all on public.%I from public,anon,authenticated',t);
 execute format('grant select on public.%I to anon,authenticated',t);
 execute format('grant insert,update,delete on public.%I to authenticated',t);
 execute format('create policy catalog_read on public.%I for select using(true)',t);
 execute format('create policy manage_catalog on public.%I for all to authenticated using ((auth.jwt()->''app_metadata''->>''belkhi_role'')=''owner'') with check ((auth.jwt()->''app_metadata''->>''belkhi_role'')=''owner'')',t);
 execute format('create trigger audit_change after insert or update or delete on public.%I for each row execute function belkhi_private.audit()',t);
 end loop;
end $$;
